-- 050 — تبلیغ تصویری روی خط لولهٔ کارکننده، و حذف نسخهٔ موازی مرده
-- ═══════════════════════════════════════════════════════════════════
-- یافتهٔ فاز ۷، از روی خودِ کد:
--
-- دو سازوکار موازی برای یک کار وجود داشت:
--
--   • `screen_messages` + `/admin/messages` — **کار می‌کند**: هدف
--     (همه/گروه/صفحه)، بازهٔ زمانی، تکرار، سه زبان، چهار سبک نمایش،
--     و تحویل واقعی در هر heartbeat.
--
--   • `campaigns` + `/admin/campaigns` — **مرده**: هیچ صفحه‌ای این
--     جدول را نمی‌خواند. بدتر، `CampaignController::broadcast()` فقط
--     پیام «دستور پخش ارسال شد» را فلش می‌کرد و هیچ کاری نمی‌کرد —
--     نه WebSocket، نه صف فرمان، نه نوشتن در دیتابیس. دکمه‌ای که
--     دروغ می‌گفت. `store()` هم هدف و تاریخ‌ها و رسانه را دور
--     می‌ریخت و `target='all'` را سخت‌کد می‌کرد.
--
-- ولی `campaigns` یک چیز داشت که `screen_messages` نداشت: `media_id`.
-- یعنی تبلیغ تصویری با هیچ‌کدام ممکن نبود — یکی ستونش را داشت و
-- تحویل نداشت، دیگری تحویل داشت و ستون نداشت.
--
-- پس: ستون رسانه به همان جدولی اضافه می‌شود که واقعا به تلویزیون
-- می‌رسد، و جدول موازی حذف می‌شود. هر دو جدول روی سرور تولید صفر
-- ردیف داشتند، پس داده‌ای از دست نمی‌رود.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE `screen_messages`
  -- تبلیغ تصویری: یک کمپین واقعی عکس یا ویدیو است، نه فقط متن
  ADD COLUMN IF NOT EXISTS `media_id` INT UNSIGNED DEFAULT NULL AFTER `icon`,
  -- کمپین در برابر اعلان: هر دو از یک لوله می‌روند ولی اپراتور باید
  -- بتواند فهرست را جدا ببیند
  ADD COLUMN IF NOT EXISTS `is_ad` TINYINT(1) NOT NULL DEFAULT 0 AFTER `media_id`;

-- کوئری تحویل در هر heartbeat اجرا می‌شود
ALTER TABLE `screen_messages`
  ADD INDEX IF NOT EXISTS `idx_msg_window` (`tenant_id`, `is_active`, `start_at`);

-- ── حذف جدول مرده ──────────────────────────────────────────────────
-- شرط قاعدهٔ بازسازی رعایت شد: ارجاع‌ها شمرده شدند و هر سه حذف شدند
-- (CampaignController حذف، مسیرها به /admin/messages هدایت، و
-- ‏ScreenMonitorService::checkExpiredCampaigns برداشته شد).
DROP TABLE IF EXISTS `campaigns`;
