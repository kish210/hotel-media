-- ════════════════════════════════════════════════════════════════════
-- نحوهٔ نمایش هر آیتم پلی‌لیست: پر کردن صفحه و صدا
-- ════════════════════════════════════════════════════════════════════
--
-- تا امروز پخش‌کننده `vid.muted = true` را ثابت در کد داشت، پس هیچ
-- ویدیویی روی هیچ تابلویی صدا نداشت و راهی هم برای روشن کردنش نبود.
-- و نسبت تصویر: ویدیویی که با صفحه جور نیست نوار خالی می‌گذارد و
-- اپراتور هیچ کنترلی روی آن نداشت.
--
-- هر دو روی **آیتم** می‌نشینند نه پلی‌لیست: در یک پلی‌لیست تبلیغاتی
-- معمولا یک تیزر باید با صدا و تمام‌صفحه پخش شود و بقیه بی‌صدا.
--
-- ── چرا muted پیش‌فرض ۱ است ─────────────────────────────────────
-- ستون `volume` از قبل وجود دارد و وسوسه‌انگیز بود که «صدا = volume>0»
-- باشد. ولی مقدار پیش‌فرضش ۱۰۰ است، و با آن تفسیر، همین مهاجرت صدای
-- همهٔ تابلوهای در حال کارِ هتل را یک‌باره روشن می‌کرد — از جمله لابی
-- و رستوران. پس یک ستون صریح با پیش‌فرض «بی‌صدا» اضافه می‌شود تا
-- رفتار امروز عوض نشود و روشن‌کردن صدا یک تصمیم آگاهانه باشد.
-- `volume` بعد از آن سطح صدا را تعیین می‌کند.
--
-- این مهاجرت idempotent است.

SET @has := (SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
              WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='playlist_items'
                AND COLUMN_NAME='fit_mode');

SET @sql := IF(@has = 0,
  "ALTER TABLE playlist_items
     ADD COLUMN fit_mode ENUM('contain','cover') NOT NULL DEFAULT 'contain'
         COMMENT 'contain نسبت تصویر را نگه می‌دارد، cover صفحه را پر می‌کند',
     ADD COLUMN muted TINYINT(1) NOT NULL DEFAULT 1
         COMMENT 'پیش‌فرض بی‌صدا — رفتار پیشین سیستم'",
  'SELECT 1');
PREPARE s FROM @sql; EXECUTE s; DEALLOCATE PREPARE s;
