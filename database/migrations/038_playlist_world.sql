-- ═══════════════════════════════════════════════════════════════════
-- 038 — تفکیک پلی‌لیست بین دو دنیا: تابلو (signage) و تلویزیون اتاق (iptv)
-- ═══════════════════════════════════════════════════════════════════
-- ‏screens از قبل screen_type داشت ولی playlists نداشت. نتیجه‌ی عملی:
-- انتخابگر پلی‌لیستِ یک تابلو، پلی‌لیست‌های IPTV را هم نشان می‌داد و
-- می‌شد محتوای اتاق را روی تابلوی لابی گذاشت.
--
-- مقدار 'any' برای پلی‌لیستی است که عمدا در هر دو دنیا استفاده می‌شود
-- (مثلا تیزر تبلیغاتی مشترک).
--
-- سطرهای موجود 'any' می‌شوند، نه 'signage': اگر پلی‌لیستی همین حالا به
-- یک صفحه‌ی IPTV وصل باشد، با پیش‌فرض signage از انتخابگر همان صفحه
-- ناپدید می‌شد و اپراتور فکر می‌کرد داده‌اش را از دست داده.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE `playlists`
  ADD COLUMN `screen_type` ENUM('signage','iptv','any') NOT NULL DEFAULT 'signage'
  COMMENT 'دنیایی که این پلی‌لیست به آن تعلق دارد';

UPDATE `playlists` SET `screen_type` = 'any' WHERE `screen_type` = 'signage';

ALTER TABLE `playlists` ADD INDEX `idx_playlists_world` (`tenant_id`, `screen_type`);
