-- ═══════════════════════════════════════════════════════════════════
-- یافتهٔ فاز ۹ از روی خودِ دیتابیس تولید:
--
-- جدول `screens` هجده ایندکس داشت و دو جفتشان عملا یکی بودند:
--
--   `code`            (code)   ←┐ دقیقا یک ستون، دو ایندکس
--   `idx_screens_code`(code)   ←┘
--
--   `idx_venue`       (venue_id)              ←┐ دومی اولی را
--   `idx_screens_venue`(tenant_id, venue_id)  ←┘ در بر می‌گیرد
--
-- چرا مهم است: هر تلویزیون هر ۳۰ ثانیه یک ضربان می‌فرستد و هر ضربان
-- همین جدول را UPDATE می‌کند (`last_seen_at`, `pending_commands`,
-- ‏`emergency_broadcast`). هر ایندکس اضافه هزینهٔ هر نوشتن است. در
-- هتل ۲۰۰ اتاقی این یعنی ۵۷۶٬۰۰۰ نوشتن در روز که بی‌دلیل گران‌ترند.
--
-- محافظه‌کارانه: فقط ایندکسی حذف می‌شود که ستون‌هایش عینا با ایندکس
-- دیگری یکی است یا پیشوندِ آن است. بقیهٔ شانزده ایندکس دست‌نخورده
-- می‌مانند، چون اثباتِ بی‌استفاده‌بودنشان بدون آمار واقعی کوئری
-- ممکن نیست و حذف ایندکسِ در حال استفاده بدتر از نگه‌داشتنش است.
--
-- ‏`code` نگه داشته می‌شود و `idx_screens_code` می‌رود: ممکن است
-- ‏`code` بخشی از یک قید UNIQUE باشد.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE `screens` DROP INDEX IF EXISTS `idx_screens_code`;
ALTER TABLE `screens` DROP INDEX IF EXISTS `idx_venue`;

-- زیرکوئری «آخرین ضربان این صفحه» در فهرست صفحه‌ها برای هر کارت اجرا
-- می‌شود: WHERE screen_id = ? ORDER BY id DESC LIMIT 1.
-- با ایندکس تک‌ستونی هم کار می‌کند، ولی ترکیبی صریح است و با هرس
-- چهارده‌روزه (artisan storage:clean) جدول را قابل‌کنترل نگه می‌دارد.
ALTER TABLE `heartbeats` ADD INDEX IF NOT EXISTS `idx_hb_screen_id` (`screen_id`, `id`);
