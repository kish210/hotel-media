-- 052 — حذف جداول مرده (بند ۳.۵ سند audit)
-- ═══════════════════════════════════════════════════════════════════
-- قاعدهٔ بازسازی: «جدول مرده فقط پس از اثبات ۰ ارجاع حذف می‌شود و در
-- همان کامیت مستند می‌شود.» اثبات، تجربی انجام شد نه از روی فهرست
-- ‏audit: هر ۸۶ جدول دیتابیس تولید گرفته شد و نامشان در کل
-- ‏app/ و resources/ و routes/ جستجو شد.
--
-- نتیجه با فهرست اولیهٔ audit فرق داشت:
--
--   • چهار نامی که audit «مرده» خوانده بود (`monitor_*`،
--     `refresh_tokens`، `screen_heartbeats`، `ws_connections`) روی
--     تولید **وجود ندارند** — آن فهرست از روی مهاجرت‌ها نوشته شده
--     بود، نه از روی دیتابیس واقعی.
--
--   • `media_subtitles` دیگر مرده نیست: در همین بازسازی به زیرنویس
--     رسانهٔ تابلو وصل شد و الان ۵ ارجاع دارد.
--
--   • `fids_airlines` صفر ارجاع دارد ولی **۱۰ ردیف دادهٔ مفید**:
--     کد IATA، نام فارسی و انگلیسی، و رنگ برند ایرلاین‌ها. جدول
--     زندهٔ `flights` فقط `airline` و `airline_logo` دارد و رنگ و
--     نام دوزبانه را ندارد. حذفش برای تیک‌زدن یک فهرست، دادهٔ
--     قابل‌استفاده را نابود می‌کرد — پس **نگه داشته شد** و به‌عنوان
--     کار باقی‌مانده ثبت شد (تابلوی پرواز می‌تواند هر ردیف را با
--     رنگ و نام فارسی ایرلاین نشان دهد).
--
-- پس فقط این پنج حذف می‌شوند: صفر ارجاع در کد **و** صفر ردیف داده.
-- ═══════════════════════════════════════════════════════════════════

-- ساختار سازمانی شرکتی — ماژول corporate هرگز این را نخواند
DROP TABLE IF EXISTS `corp_departments`;

-- نسخهٔ قدیمی جدول پرواز. دادهٔ زنده در `flights` است (۷ ارجاع).
DROP TABLE IF EXISTS `fids_flights`;

-- فروشگاه خرده‌فروشی — طرحی که پیاده نشد
DROP TABLE IF EXISTS `retail_products`;

-- برنامهٔ حمل‌ونقل — هرگز به تابلو وصل نشد
DROP TABLE IF EXISTS `transport_schedules`;

-- توکن کاربر: احراز هویت از JWT بی‌حالت استفاده می‌کند و این جدول
-- از ابتدا بی‌مصرف ماند
DROP TABLE IF EXISTS `user_tokens`;
